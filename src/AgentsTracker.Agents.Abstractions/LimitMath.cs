namespace AgentsTracker.Agents;

/// <summary>
/// Единственное правило округления доли окна в проценты — на весь шлюз: расход вверх до целого
/// и обрезка в 0..100, остаток — вычитанием из ста, а не своим округлением. Правило одно, потому
/// что цифры одного и того же окна показываются в трёх местах (шкалы <c>/status</c>, шапка меню,
/// монитор), и независимые округления расходились на 14 значениях из 1001: «расход 67% ·
/// осталось 32%» в одном сообщении. Вверх — чтобы не обнадёживать: 0.1% расхода показывается как
/// «1%», а «осталось 0%» появляется чуть раньше настоящего нуля (на 99.5% окно ещё пускает запуск).
/// Доля обязательно <c>decimal</c>: у double 0.67 * 100 равно 67.00000000000001, и правило
/// пришлось бы поправлять на 1e-9 в каждом месте, где его повторяют.
/// </summary>
public static class LimitMath
{
    /// <summary>Израсходованная доля окна 0..1 в проценты 0..100.</summary>
    public static int Percent(decimal used) => Math.Clamp((int)Math.Ceiling(used * 100), 0, 100);

    /// <summary>Остаток окна в процентах: ровно то, что не попало в <see cref="Percent"/>.</summary>
    public static int Left(decimal used) => 100 - Percent(used);
}
